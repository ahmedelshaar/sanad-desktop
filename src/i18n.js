export const dictionaries = { ar, en };

export const I18nContext = createContext({ lang: 'ar', t: (k) => ar[k] || k, setLang: () => {} });

export function useI18n() {
  return useContext(I18nContext);
}

export function makeT(lang) {
  const dict = dictionaries[lang] || ar;
  return (key) => dict[key] ?? ar[key] ?? key;
}

export function errorText(t, code) {
  const key = `err_${code}`;
  const msg = t(key);
  return msg === key ? `${t('err_generic')}: ${code}` : msg;
}
